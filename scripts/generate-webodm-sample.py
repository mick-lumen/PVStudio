#!/usr/bin/env python3
"""Generate and validate the deterministic PV Studio WebODM-style fixture.

The real ODMData catalogue publishes the aerial source photographs and asks
users to run ODM locally; it does not publish a small, redistributable OBJ
bundle.  This fixture therefore keeps the same output contract (OBJ + MTL +
JPEG texture maps) while remaining reproducible and easy to load from the
browser.  Geometry is a lightly noisy house/roof/ground scene, rather than a
placeholder cube, so surface picking and roof placement can be exercised.

Usage:
    python3 scripts/generate-webodm-sample.py
    python3 scripts/generate-webodm-sample.py --validate

The generator intentionally has no third-party Python dependencies.  JPEG
maps are produced through ffmpeg when available and a tiny valid fallback map
is emitted when it is not; the checked-in fixture is generated with ffmpeg.
"""

